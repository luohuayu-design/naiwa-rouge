// 看过任意一夜就算解锁（番外之间也有先后逻辑，所以有的用 after，有的用 both）
function seen(ctx, id) {
  const s = ctx && ctx.story;
  if (!s) return false;
  return !!((s.seen && s.seen[id]) || (s.read && s.read[id]));
}
const after = (ctx, ...ids) => ids.some((id) => seen(ctx, id));
const both = (ctx, ...ids) => ids.every((id) => seen(ctx, id));

