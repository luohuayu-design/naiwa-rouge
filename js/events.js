// ============================================================
// events.js —— 夜行奇遇（回合结束的抉择）
//
// 规则（第 7 块，用户定案）：
//   · 每回合**结束**时弹一次，效果作用于**下一回合**（回合结束自动撤销）；
//   · 每个事件都有一个具体的人 + 一段处境 + 2~4 个各有代价的选项；
//   · 选择会改「民心」（0~100）：民心高，商店便宜、村民帮你；民心低，涨价、遭贼；
//   · 6 条连锁线会跨 2~3 回合兑现（报恩 / 报复 / 病情 / 商队 / 井神 / 俘虏）。
//
// 单个事件的结构（两种形态，可以只有一种）：
//   A. 一次抉择（大多数事件）
//   { id, icon, title, who, story, weight?, cond?(ctx), chainOnly?,
//     choices: [{ label, hint, cost?, effects, say?, chain? }] }
//
//   B. 对话（第 10 块，可以来回好几轮）
//   { id, icon, title, who, story,
//     talk: [ { who?, say, replies: [ { label, say, close?, hint?, cost?,
//                                      effects?, chain?, go? } ] } ] }
//     · 每一「拍」= 对方说一句（say）+ 你可以回的几句（replies）；
//     · 你的回话写 say（会作为「你」的气泡留在对话记录里），
//       对方听完的反应写 close（结束时再补一句）；
//       对方接下来还要说更多，就 go: 1（跳到第 2 拍，下标从 0 算）；
//     · 不带 go = 这一拍就是最后一句，选完直接进结算；
//     · 每一拍的代价/收益照旧走 cost / effects，多拍的选择会**累积**到同一份结算里
//       （民心、金币、属性都在结算那一刻一起落，金币/生命则当场就扣）。
//     · 有 talk 的事件不用再写 choices。
//
// 预留：以后的小游戏（打地鼠、拍节奏……）以 `miniGame: '<id>'` 挂在选项上，
//       main.js 里留了接入口（见 openMiniGame 的空实现），本块先不做。
//
// effects（main.js 负责落地，全部作用于**下一回合**）：
//   rep    ±n                      民心（永久，跨回合记住）
//   gold   ±n                      立刻结算金币
//   hp     ±n                      立刻结算生命（负数保底 0.5）
//   drain  n                       下一回合每秒流失生命
//   level  {countScale, speedScale} 下一回合怪物数量 / 移速倍率
//   mods   [{stat, flat?, pct?, scope?}] 下一回合临时属性
//   permanent [{stat, flat?, pct?}]      永久属性（跨回合记住，如幸运 / 金币掉落率）
//   healFull true                  立刻回满生命
//   discount 0.2                   下一次商店打 8 折（用掉即清，可与民心折扣叠）
//   chain  { in, id }              在选项里写：in 回合后强制弹出 id 事件
//   roll   [{p, effects}, ...]     选项内部的概率分支
//
// 第 83 块（用户要求）：下面 mods / level 这些**只活一回合**的数值，在模块加载时
//   会被统一放大一次（倍数表 TEMP_SCALE / TEMP_LEVEL，在文件末尾「临时效果放大」那段），
//   hint 里的数字同步重算 —— 所以表里写 0.2，玩家看到和实际生效的可能是 0.6。
//   drain（每秒掉血）不放大：它本来就是这批选项里最疼的代价。
//
// ctx: { round, hasWeapon, gold, rep, hp, maxHp, luck }
//   luck 用来写 cond（幸运够高才遇得到的吉兆事件，第 11 块）。
// ============================================================
