// 把 effects 翻译成事件卡上能直接展示的几行字（统一说「下回合」）
function modLine(m) {
  // 两块属性表都查：武器项（剑转速等）在 WEAPON_STAT_DEFS 里
  const def = (m.scope === 'weapon' ? WEAPON_STAT_DEFS : STAT_DEFS).find((d) => d.key === m.stat)
    || STAT_DEFS.find((d) => d.key === m.stat)
    || WEAPON_STAT_DEFS.find((d) => d.key === m.stat);
  const name = def ? def.name : m.stat;
  if (m.pct != null) return `${name} ${(m.pct >= 0 ? '+' : '')}${(m.pct * 100).toFixed(1)}%（下回合）`;
  return `${name} ${(m.flat >= 0 ? '+' : '')}${m.flat.toFixed(1)}（下回合）`;
}

export function effectLines(effects = {}) {
  const lines = [];
  for (const m of effects.mods || []) lines.push(modLine(m));
  for (const m of effects.permanent || []) {
    const def = STAT_DEFS.find((d) => d.key === m.stat) || WEAPON_STAT_DEFS.find((d) => d.key === m.stat);
    const name = def ? def.name : m.stat;
    if (m.pct != null) {
      lines.push(`${name} ${m.pct >= 0 ? '+' : ''}${(m.pct * 100).toFixed(1)}%（永久）`);
    } else {
      // 用属性表自己的格式：金币掉落率写成「+6.0%」，幸运写成「+1.0」，攻击力写成「+1.0」
      const v = m.flat ?? 0;
      const text = def && typeof def.fmt === 'function' ? def.fmt(v) : v.toFixed(1);
      lines.push(`${name} ${v >= 0 ? '+' : ''}${text}（永久）`);
    }
  }
  // 第 87 块：正向回血统一成「生命上限 +N 且补 N」，文案跟着说清，
  // 否则玩家会以为还是即时补血、满血时选它等于没选。
  // 「生命回满」没有点数，统一抬 2 点上限再补满（与 main.js 的 HEALFULL_UP 联动）。
  if (effects.healFull) lines.push('生命上限 +4 · 生命回满');
  if (effects.discount) {
    lines.push(effects.discount > 0
      ? `下次商店 ${Math.round((1 - effects.discount) * 10)} 折`
      : `下次商店涨价 ${Math.round(-effects.discount * 100)}%`);   // 第 62 块：负折扣 = 涨价
  }
  if (effects.rep > 0) lines.push(`民心 +${effects.rep}`);
  if (effects.rep < 0) lines.push(`民心 ${effects.rep}`);
  if (effects.gold > 0) lines.push(`金币 +${effects.gold}`);
  if (effects.gold < 0) lines.push(`金币 ${effects.gold}`);
  if (effects.hp > 0) lines.push(`生命上限 +${effects.hp.toFixed(1)}（补满）`);
  if (effects.hp < 0) lines.push(`生命 ${effects.hp.toFixed(1)}`);
  if (effects.drain > 0) lines.push(`每秒生命 -${effects.drain.toFixed(1)}（下回合）`);
  if (effects.level?.countScale != null) lines.push(`下回合怪物数量 ×${effects.level.countScale}`);
  if (effects.level?.speedScale != null) lines.push(`下回合怪物移速 ×${effects.level.speedScale}`);
  return lines;
}

// ---------------- 对话式事件（第 10 块） ----------------
export function isTalk(ev) {
  return !!(ev && ev.talk && ev.talk.length);
}

// 一个事件里「所有能落的选项」：对话事件 = 每一拍的所有回话
// （文档生成与单元测试都走这个口，两种形态一视同仁）
export function eventChoices(ev) {
  if (!ev) return [];
  if (isTalk(ev)) return ev.talk.flatMap((b) => b.replies || []);
  return ev.choices || [];
}

// 概率分支：在**选中的那一刻**摇一次，返回具体效果
// （对话会把好几拍的效果累积到同一份结算里，所以得先把 roll 拆开）
export function resolveRoll(effects, rng = Math.random) {
  if (!effects || !effects.roll) return effects || {};
  let r = rng();
  let picked = effects.roll[effects.roll.length - 1];
  for (const b of effects.roll) {
    r -= b.p;
    if (r < 0) { picked = b; break; }
  }
  return resolveRoll(picked.effects, rng);
}

// 把 b 合进 a：数字相加、mods/permanent 相接、level 倍率相乘
// （对话里每一拍选的效果，最后一起结算成一张账单）
export function mergeEffects(a, b) {
  const out = a || {};
  if (!b) return out;
  for (const k of ['rep', 'gold', 'hp', 'drain']) {
    if (b[k]) out[k] = (out[k] || 0) + b[k];
  }
  if (b.mods && b.mods.length) out.mods = (out.mods || []).concat(b.mods);
  if (b.permanent && b.permanent.length) out.permanent = (out.permanent || []).concat(b.permanent);
  if (b.level) {
    out.level = out.level || {};
    if (b.level.countScale != null) out.level.countScale = (out.level.countScale ?? 1) * b.level.countScale;
    if (b.level.speedScale != null) out.level.speedScale = (out.level.speedScale ?? 1) * b.level.speedScale;
  }
  return out;
}

// 选项按钮上的说明（hint 已经写好了就用它，否则从 effects 推）
export function choiceHint(choice) {
  if (choice.hint) return choice.hint;
  const lines = effectLines(choice.effects || {});
  return lines.length ? lines.join(' · ') : '无变化';
}

// 代价是否付得起（金币 / 生命）
export function canAfford(choice, { gold = 0, hp = 99 } = {}) {
  const c = choice.cost || {};
  if (c.gold != null && gold < c.gold) return false;
  if (c.hp != null && hp <= c.hp) return false;
  return true;
}

export function costShort(choice) {
  const c = choice.cost || {};
  const out = [];
  if (c.gold) out.push(`${c.gold} 金币`);
  if (c.hp) out.push(`${c.hp} 生命`);
  return out.join(' + ');
}
