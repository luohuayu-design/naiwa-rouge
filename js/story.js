// ============================================================
// story.js —— 主线《奶蛙夜行 · 笑不出来的那一夜》（第 32 块）
//
// 为什么单独一个文件：
//   随机奇遇（events.js）是「抽签」——每次都不一样；
//   主线是「顺序」——玩家走到哪一夜，就必须遇到那一夜。
//   两者的数据结构很像（都是对话卡），但调度规则完全相反，混在一起会互相踩。
//
// 结构：一卷 = 18 夜。**一夜对应一关**。
//   第 1 / 2 / 3 夜已经有实装关卡（草甸 / 骨塔 / 焦土钟楼），
//   打完那一关的指定回合就会撞上相应的夜；
//   第 4 ~ 18 夜是给后面那 15 关预留的剧本，现在只能在
//   主菜单「夜行记忆」里当档案读（levelId 为 null）。
//
// 加新关卡时要做的事只有两件：
//   1) 把对应章节的 levelId 从 null 改成新关卡 id；
//   2) 填 atRound（这一夜在那一关的第几回合结束后发生）。
//   调度代码一行都不用改 —— storyChapterAt() 自己会认。
//
// 印记（mark）：
//   第 1 / 2 / 3 夜各有一个「空白」的收账抉择，玩家必须交出一样东西：
//   laughter（笑声）/ name（名字）/ memory（记忆）。
//   三次累计决定第 18 夜的结局，见 storyEndingKey()。
// ============================================================

