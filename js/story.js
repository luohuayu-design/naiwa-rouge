// 按 id 找一章
export function storyChapterById(id) {
  return STORY_CHAPTERS.find((c) => c.id === id) || null;
}

// 某一关、某个回合该不该播主线：返回**最早一个还没看过**的章节。
// 这样即使玩家读档跳过回合、或一口气打到很后面，也不会漏掉剧情。
export function storyChapterAt(levelId, roundNo, seen = {}) {
  if (!levelId) return null;
  const pool = STORY_CHAPTERS
    .filter((c) => c.levelId === levelId && c.atRound != null && c.atRound <= roundNo && !seen[c.id])
    .sort((a, b) => a.atRound - b.atRound);
  return pool[0] || null;
}

// 已解锁的章节（局内看过的 + 手动解锁的）
export function storySeenCount(seen = {}) {
  return STORY_CHAPTERS.filter((c) => seen[c.id]).length;
}
