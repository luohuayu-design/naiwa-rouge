//   某一项 >= 2  → 对应结局
//   三项各 1     → 隐藏结局（它什么都没多交，也什么都没少交）
//   一次都没交   → 也是隐藏结局（它一次都没低头）
// ------------------------------------------------------------
export function storyEndingKey(marks = {}) {
  const l = marks.laughter || 0;
  const n = marks.name || 0;
  const m = marks.memory || 0;
  const total = l + n + m;
  if (total === 0) return 'none';
  if (l >= 2) return 'laughter';
  if (n >= 2) return 'name';
  if (m >= 2) return 'memory';
  return 'none';
}

