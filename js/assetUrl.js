// ============================================================
// 静态资产 → 拼上当前代码版本号（第 80 块）
// ============================================================
// 为什么要有这个文件：Service Worker（第 79 块）对资源分两档
//   · 带 `?v=N` 的 → **缓存优先**（同版本的 URL 内容不可变，读缓存永不发请求）
//   · 不带版本号的 → 先用缓存 + **后台重下一遍**（因为文件名不跟版本走，可能被替换）
//
// 问题就出在第二档：怪物 glb 一共 7MB，文件名不带版本号。于是每次刷新、
// 每次重新进关，SW 都会在后台把这 7MB 重新下一遍 —— 玩家正在进关，
// 带宽被自己抢光，就是「每一关的加载还是很慢」的另一半原因（第 80 块实测）。
//
// 而模型其实只在发版时才换。所以给 glb 请求拼上 `?v=N`，它立刻升级到第一档：
//   · 同一版本第二次进 → Cache Storage 直读，一个字节都不下；
//   · 换版本 → URL 变了，天然拿新模型（第 77 块换模型"看着像没换"的坑一起堵掉）。
//
// 版本号**不写死**：这个模块自己的 URL 上就带着（index.html 里所有 import 都带 ?v=N），
// 所以只要发版时按铁律一起 bump，这里自动拿到新值。
// 万一哪天忘了 bump、import 没带版本，ASSET_V 就是空串 → 退回原路径（旧行为），不会崩。
export const ASSET_V = (() => {
  try {
    return new URL(import.meta.url).searchParams.get('v') || '';
  } catch (_) {
    return '';
  }
})();

// 已经带版本号的（用正则判断，不按字面比）原样返回，别重复拼成两截
export function withV(path) {
  if (!ASSET_V || !path) return path;
  if (/[?&]v=\d+/.test(path)) return path;
  return path + (path.includes('?') ? '&' : '?') + 'v=' + ASSET_V;
}
