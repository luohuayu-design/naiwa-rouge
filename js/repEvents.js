// ============================================================
// repEvents.js —— 民心专属事件（第 62 块，用户需求）
//
// 为什么单独一个池子：
//   普通奇遇是「路边随便遇到的一件事」，和民心只是**加减关系**；
//   这一批事件是**民心本身长出来的后果** —— 你被村里人记住了，或者被记住了恨。
//   所以它们不进随机池（全部标 chainOnly），只由 main.js 的「档位变化队列」点名播放：
//     民心升到 60 / 80 / 100 → 从良性池里抽一条（给一个本局持续的 buff）
//     民心跌到 40 / 20      → 从恶性池里抽一条（附带麻烦）
//   同一档一局只触发一次（main.js 的 repEvFired 去重），所以不会反复刷。
//
// 文案要求和其它事件一致：一个具体的人 + 一段处境 + 几句话说清前因后果，
// 对话普遍 100~180 字（用户 2026-10-22 定过）。
// ============================================================

