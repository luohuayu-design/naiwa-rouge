// tier → 该档该抽哪个池子（main.js 的档位变化队列按这个查）
// 返回 null 表示这一档没有专属事件
export function repPoolForTier(tier) {
  if (tier >= 1) return REP_GOOD.filter((e) => e.tier === Math.min(3, tier));
  if (tier <= -1) return REP_BAD.filter((e) => e.tier === Math.max(-2, tier));
  return null;
}
